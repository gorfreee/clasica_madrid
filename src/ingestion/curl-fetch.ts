import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const run = promisify(execFile);
/** Public CDCM only. A conventional curl GET, with its real default User-Agent.
 * No shell, redirect following, origin-host access, cookies or relay credentials.
 */
export async function getCdcmWithCurl(url: string, timeoutMs: number): Promise<string> {
  const target = new URL(url);
  const viewName = target.searchParams.get('view_name');
  const site = viewName === 'tdc_show_search' ? 'teatroscanal' : viewName === 'te_show_search' ? 'auditorioescorial' : undefined;
  const isAjax = target.pathname === '/views/ajax' && site !== undefined &&
    target.searchParams.get('view_display_id') === 'page_show_schedule_search' &&
    [ `/${site}/programacion`, ...(site === 'teatroscanal' ? [`/${site}/programacion/categoria/musica`] : []) ].includes(target.searchParams.get('view_path') ?? '') &&
    target.searchParams.get('view_base_path') === `${site}/programacion` && target.searchParams.get('view_args') === '' &&
    target.searchParams.get('pager_element') === '0' && target.searchParams.get('_wrapper_format') === 'drupal_ajax' &&
    target.searchParams.get('_drupal_ajax') === '1' && /^[a-f0-9]{64}$/.test(target.searchParams.get('view_dom_id') ?? '') &&
    /^\d{1,2}$/.test(target.searchParams.get('page') ?? '') && Number(target.searchParams.get('page')) < 20;
  if(target.origin !== 'https://www.cdcm.madrid' || target.username || target.password || target.hash ||
    (!isAjax && !/^\/(?:teatroscanal|auditorioescorial)\/(?:programacion(?:\/categoria\/musica)?|espectaculo\/[a-z0-9-]+)$/.test(target.pathname))) {
    throw new Error('CDCM: URL pública no permitida para curl');
  }
  let stdout: string;
  try {
    ({ stdout } = await run('curl', ['--disable', '--globoff', '--silent', '--show-error', '--proto', '=https',
      '--connect-timeout', '10', '--max-time', String(Math.max(1, timeoutMs / 1000)),
      '--max-filesize', '4000000', '--write-out', '\n%{json}', '--url', target.href],
      { encoding: 'utf8', maxBuffer: 4_100_000, timeout: timeoutMs + 1000 }));
  } catch(error) {
    const code = error && typeof error === 'object' && 'code' in error ? error.code : undefined;
    throw new Error(code === 28 ? `tiempo agotado al pedir ${url} con curl` : `CDCM: curl no pudo descargar ${url} (código ${String(code)})`);
  }
  const boundary = stdout.lastIndexOf('\n');
  let meta: { http_code?: unknown; content_type?: unknown; url_effective?: unknown };
  try { meta = JSON.parse(stdout.slice(boundary + 1)); }
  catch { throw new Error('CDCM: metadata de curl inválida'); }
  if(meta.http_code !== 200) throw Object.assign(new Error(`HTTP ${String(meta.http_code)} al pedir ${url} con curl`), { status: meta.http_code });
  if(meta.url_effective !== target.href || typeof meta.content_type !== 'string' || !(isAjax ? /^application\/json(?:;|$)/i : /^text\/html(?:;|$)/i).test(meta.content_type)) {
    throw new Error('CDCM: respuesta curl fuera del contrato del documento oficial');
  }
  const body = stdout.slice(0, boundary);
  if(!body.trim() || /<title>\s*ERROR:|Generated by cloudfront|\bsgcaptcha\b/i.test(body)) throw new Error('CDCM: documento vacío o bloqueado');
  return body;
}
