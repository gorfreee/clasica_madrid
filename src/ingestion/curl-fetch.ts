import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const run = promisify(execFile);
/** Public CDCM only. A conventional curl GET, with its real default User-Agent.
 * No shell, redirect following, origin-host access, cookies or relay credentials.
 */
export async function getCdcmWithCurl(url: string, timeoutMs: number): Promise<string> {
  const target = new URL(url);
  if (target.origin !== 'https://www.cdcm.madrid' || target.username || target.password ||
      !/^\/(?:teatroscanal|auditorioescorial)\/(?:programacion(?:\/categoria\/musica)?|espectaculo\/[a-z0-9-]+)$/.test(target.pathname)) {
    throw new Error('CDCM: URL pública no permitida para curl');
  }
  let stdout: string;
  try {
    ({ stdout } = await run('curl', ['--silent', '--show-error', '--proto', '=https',
      '--connect-timeout', '10', '--max-time', String(Math.max(1, timeoutMs / 1000)),
      '--max-filesize', '4000000', '--write-out', '\n%{json}', '--url', target.href],
    { encoding: 'utf8', maxBuffer: 4_100_000, timeout: timeoutMs + 1000 }));
  } catch (error) {
    const code = error && typeof error === 'object' && 'code' in error ? error.code : undefined;
    throw new Error(code === 28 ? `tiempo agotado al pedir ${url} con curl` : `CDCM: curl no pudo descargar ${url} (código ${String(code)})`);
  }
  const boundary = stdout.lastIndexOf('\n');
  let meta: { http_code?: unknown; content_type?: unknown; url_effective?: unknown };
  try { meta = JSON.parse(stdout.slice(boundary + 1)); }
  catch { throw new Error('CDCM: metadata de curl inválida'); }
  if (meta.http_code !== 200) throw Object.assign(new Error(`HTTP ${String(meta.http_code)} al pedir ${url} con curl`), { status: meta.http_code });
  if (meta.url_effective !== target.href || typeof meta.content_type !== 'string' || !/^text\/html(?:;|$)/i.test(meta.content_type)) {
    throw new Error('CDCM: respuesta curl fuera del contrato HTML oficial');
  }
  const body = stdout.slice(0, boundary);
  if (!body.trim() || /<title>\s*ERROR:|Generated by cloudfront|\bsgcaptcha\b/i.test(body)) throw new Error('CDCM: documento vacío o bloqueado');
  return body;
}
